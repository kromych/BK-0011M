/// Russian capitals drawn like Latin ones.
const SAME_AS_LATIN: &[(char, char)] = &[
    ('А', 'A'),
    ('В', 'B'),
    ('Е', 'E'),
    ('К', 'K'),
    ('М', 'M'),
    ('Н', 'H'),
    ('О', 'O'),
    ('Р', 'P'),
    ('С', 'C'),
    ('Т', 'T'),
    ('Х', 'X'),
];

/// The rows of a character, 5 bits each (bit 4 = leftmost); unknown
/// characters draw as a box.
fn glyph(c: char) -> [u8; HEIGHT] {
    static TABLE: OnceLock<HashMap<char, [u8; HEIGHT]>> = OnceLock::new();
    let table = TABLE.get_or_init(|| {
        let mut t: HashMap<char, [u8; HEIGHT]> = GLYPHS
            .iter()
            .map(|(c, rows)| {
                let mut bits = [0; HEIGHT];
                for (b, row) in bits.iter_mut().zip(rows) {
                    *b = row
                        .bytes()
                        .fold(0, |acc, p| (acc << 1) | u8::from(p == b'#'));
                }
                (*c, bits)
            })
            .collect();
        for &(ru, lat) in SAME_AS_LATIN {
            let g = t[&lat];
            t.insert(ru, g);
        }
        t
    });
    table.get(&c).copied().unwrap_or([
        0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111,
    ])
}

/// Width in pixels of `text` drawn with [`draw`].
pub fn width(text: &str) -> usize {
    (text.chars().count() * ADVANCE).saturating_sub(1)
}

/// Draw `text` with its top-left corner at (x, y); clipped to the buffer.
pub fn draw(buf: &mut [u32], buf_width: usize, x: usize, y: usize, text: &str, color: u32) {
    let height = buf.len() / buf_width;
    for (i, c) in text.chars().enumerate() {
        let gx = x + i * ADVANCE;
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..5 {
                let (px, py) = (gx + col, y + row);
                if bits & (0b10000 >> col) != 0 && px < buf_width && py < height {
                    buf[py * buf_width + px] = color;
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        for (c, rows) in GLYPHS {
            assert!(
                rows.iter()
                    .all(|r| r.len() == 5 && r.bytes().all(|b| b == b'.' || b == b'#')),
                "{c:?}"
            );
        }
        let mut seen = std::collections::HashSet::new();
        assert!(GLYPHS.iter().all(|(c, _)| seen.insert(*c)), "no duplicates");
        // Every Russian capital has a glyph.
        for c in 'А'..='Я' {
            assert_ne!(glyph(c), glyph('\u{1}'), "{c}");
        }
    }

    #[test]
    fn draws_and_clips() {
        let mut buf = vec![0; 20 * 10];
        draw(&mut buf, 20, 0, 0, "I", 1);
        assert_eq!(buf[1..4], [1, 1, 1], "top bar of I");
        draw(&mut buf, 20, 18, 8, "WW", 2); // mostly off the edge
        assert_eq!(width("ABC"), 17);
    }
}
